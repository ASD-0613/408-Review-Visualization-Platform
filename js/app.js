/* ============================================================================
 * 导航渲染与启动
 * ========================================================================== */
(function boot() {
  let curBook = 'ds';
  let curTopic = null;
  let curFilter = 'all';   // 侧栏筛选：all | ready | other
  /* 窗41：索引页的"当前年份"（侧栏年份按钮用；null = 全部年份） */
  let curIndexYear = null;

  const tabsEl = document.getElementById('main-tabs');
  const sidebarEl = document.getElementById('sidebar');
  const mobileEl = document.getElementById('mobile-nav');
  const catalogTitleEl = document.getElementById('catalog-title');
  const catalogHintEl = document.getElementById('catalog-hint');
  const mainSectionEl = document.getElementById('main-section');
  const indexSectionEl = document.getElementById('exam-index-section');

  /** 顶部页签（四本书 + 最左的「真题总览」；索引页签自己占满一排，见 .tab-index） */
  function renderTabs() {
    tabsEl.innerHTML = RC408.books.map(b => {
      if (b.kind === 'index') {
        return `<button data-book="${b.id}" class="tab-btn tab-index ${b.id === curBook ? 'tab-active' : ''}"
          title="真题总览：按年份 × 题号看全部真题，点方块跳到对应模块">
          <span>${b.icon}</span><span>${b.name}</span>
        </button>`;
      }
      const ready = b.chapters.flatMap(c => c.topics).filter(t => t.status === 'ready').length;
      const total = b.chapters.reduce((n, c) => n + c.topics.length, 0);
      return `<button data-book="${b.id}" class="tab-btn ${b.id === curBook ? 'tab-active' : ''}">
        <span>${b.icon}</span><span>${b.name}</span>
        <span class="tab-badge" title="已实现 / 总数">${ready}/${total}</span>
      </button>`;
    }).join('');
    tabsEl.querySelectorAll('[data-book]').forEach(btn => {
      btn.addEventListener('click', () => selectBook(btn.dataset.book));
    });
  }

  /** 左侧子导航树（章节分组 → 知识点条目；支持 可交互/未上线 筛选） */
  function renderSidebar() {
    const book = RC408.books.find(b => b.id === curBook);
    if (book.kind === 'index') { renderIndexSidebar(); return; }
    const matchFilter = t => curFilter === 'all'
      || (curFilter === 'ready' && t.status === 'ready')
      || (curFilter === 'theory' && t.status === 'theory')
      || (curFilter === 'wip' && t.status !== 'ready' && t.status !== 'theory');
    const filterBar = `
      <div class="sticky top-0 z-10 bg-white/95 backdrop-blur px-3 pt-3 pb-2 border-b border-slate-100">
        <div class="flex gap-1">
          ${[['all', '全部'], ['ready', '✓ 可交互'], ['theory', '纯理论'], ['wip', '建设中']].map(([v, t2]) =>
            `<button data-filter="${v}" class="flex-1 text-[11px] font-bold py-1.5 rounded-lg transition-colors ${curFilter === v ? 'bg-indigo-500 text-white shadow-sm' : 'bg-slate-100 text-slate-500 hover:bg-slate-200'}">${t2}</button>`).join('')}
        </div>
      </div>`;
    /* 火苗徽标（两级）：hot2 = 用户提供的「热门考点排行榜」前 15 名（最热）；hot = 真题统计口径的高频考点。
       ⚠ 判据见 §1.5：**hot2 ⟹ hot**（双火苗必须踩在单火苗上），由 `node tmp_dup_audit.js hot2` 机器复核。
       排行榜口径与 examHistory 口径**不是一回事**：hot 一律由 examHistory 现算，hot2 按用户给的名次表落库。 */
    const flame = t => t.hot2
      ? '<span class="wip-badge" style="background:#fee2e2;color:#b91c1c" title="最热考点（热门考点排行榜前 15 名）">🔥🔥</span>'
      : (t.hot ? '<span class="wip-badge" style="background:#fff1f2;color:#be123c" title="真题高频考点">🔥</span>' : '');
    sidebarEl.innerHTML = filterBar + book.chapters.map(ch => {
      const topics = ch.topics.filter(matchFilter);
      if (!topics.length) return '';
      return `
      <div class="px-4 pt-4 pb-1 text-[11px] font-bold text-slate-400 tracking-wider">${ch.name}</div>
      ${topics.map(t => t.status === 'ready'
        ? `<button data-topic="${t.id}" class="topic ${t.id === curTopic ? 'topic-active' : ''}">
             <span class="dot"></span><span>${t.label}</span>${flame(t)}
           </button>`
        /* ⚠ 三种"非 ready"状态要用**两套**外观，别一律 topic-wip（用户 2026-09-25 反馈）：
             · theory（纯理论速记卡）：**内容已完成**，只是没有交互动画 ⟹ 标题用正常黑字、圆点用蓝点，
               与"可交互"齐平（用户原话："标题文字可以变成黑色（和可交互一样），然后前面灰点改成蓝点"）；
             · wip（建设中 / 考纲外）：确实还没有内容 ⟹ 保持灰色弱化。
           判据：**已完工的绝不做视觉弱化**——这与 §1.5 那条"已完工内容绝不显示敬请期待"是同一条纪律。 */
        : `<button data-topic="${t.id}" class="topic ${t.status === 'theory' ? 'topic-theory' : 'topic-wip'} ${t.id === curTopic ? 'topic-active' : ''}"
             title="${t.legacy ? '该考点已从现行考纲删除，点击查看说明' : t.status === 'theory' ? '纯理论速记卡（已完成，无交互动画）' : '点击查看规划中的内容'}">
             <span class="${t.status === 'theory' ? 'dot dot-theory' : 'w-1.5 h-1.5 rounded-full bg-slate-300 shrink-0'}"></span>
             <span>${t.label}</span>${t.legacy
              ? '<span class="wip-badge" style="background:#fff1f2;color:#9f1239" title="真题曾考，现行考纲已删">考纲外</span>'
              : (t.status === 'theory' ? '<span class="wip-badge" style="background:#e0f2fe;color:#0369a1" title="纯理论速记卡（已完成）">📖 纯理论</span>' : '') + (flame(t) || (t.status === 'theory' ? '' : '<span class="wip-badge">敬请期待</span>'))}
           </button>`).join('')}`;
    }).join('');
    sidebarEl.querySelectorAll('[data-topic]').forEach(btn => {
      btn.addEventListener('click', () => openTopic(btn.dataset.topic));
    });
    sidebarEl.querySelectorAll('[data-filter]').forEach(btn => {
      btn.addEventListener('click', () => { curFilter = btn.dataset.filter; renderSidebar(); });
    });

    // 移动端横向导航
    mobileEl.innerHTML = book.chapters.flatMap(c => c.topics).map(t =>
      `<button data-topic="${t.id}" class="shrink-0 px-3 py-1.5 rounded-lg text-xs font-bold ${t.id === curTopic ? 'bg-indigo-500 text-white' : t.status === 'ready' ? 'bg-slate-800 text-indigo-200' : 'bg-slate-800/60 text-slate-500'}">${t.label}${t.status === 'ready' ? '' : ' 🚧'}</button>`
    ).join('');
    mobileEl.querySelectorAll('[data-topic]').forEach(btn => {
      btn.addEventListener('click', () => openTopic(btn.dataset.topic));
    });
  }

  /** 切换主 Tab（书籍），自动打开该书第一个可用知识点；索引页签则切到真题总览 */
  function selectBook(bookId) {
    curBook = bookId;
    const book = RC408.books.find(b => b.id === bookId);
    renderTabs();
    if (book.kind === 'index') {
      /* 索引页：不打开任何模块（也就不会触发 Runner 重绘），只切视图 */
      curTopic = null;
      showIndex();
      return;
    }
    showMain();
    const all = book.chapters.flatMap(c => c.topics);
    const first = all.find(t => t.status === 'ready') || all[0];
    openTopic(first.id);
  }

  /** 打开某个知识点（更新侧栏高亮 → 交给 Runner 渲染工作区） */
  function openTopic(topicId) {
    curTopic = topicId;
    /* 从真题总览点方块跳过来时，当前页签可能还是 index ⟹ 让页签跟随目标所属的书，
       否则会出现"页签停在真题总览、右侧却是某个模块"的错位（侧栏也会渲染错）。 */
    const hit = (function () {
      for (const b of RC408.books) for (const c of b.chapters) {
        const t = c.topics.find(x => x.id === topicId);
        if (t) return { book: b, topic: t };
      }
      return null;
    })();
    if (hit && hit.book.id !== curBook) {
      curBook = hit.book.id;
      renderTabs();
    }
    showMain();
    renderSidebar();
    Runner.open(topicId);
  }
  // 供专注模式下拉选择器调用（同步侧栏高亮）
  RC408.openTopicFromUI = openTopic;

  /* ---------------- 真题总览（题目-模块索引）页：视图切换 ---------------- */
  let indexModel = null;

  /** 显示索引页（隐藏主展示区；每次都重新 mount —— 那是纯拼字符串，开销可忽略） */
  function showIndex() {
    if (!RC408.examIndexPage) return;
    /* 专注模式与本页不兼容（它会隐藏主区与目录、只留操作/图像两栏）⟹ 先退出 */
    if (Runner.focusMode) Runner.exitFocus();
    mainSectionEl.classList.add('hidden');
    indexSectionEl.classList.remove('hidden');
    if (!indexModel) {
      indexModel = RC408.examIndexPage.prepare(RC408.examIndex || [], RC408.examHistory || {}, RC408.books);
      setCatalogHead('🗓 年份快速定位', '矩阵<strong>最新年份在最上</strong>（2026 → 2009），与本列表同序；点年份跳到对应那一行。');
    }
    renderSidebar();      // 侧栏改画「年份快速定位」（curBook === 'index' 时 renderSidebar 会走索引分支）
    RC408.examIndexPage.mount(indexModel);
  }

  /** 显示主展示区（回到某个模块页） */
  function showMain() {
    if (RC408.examIndexPage) RC408.examIndexPage.closePop();
    indexSectionEl.classList.add('hidden');
    mainSectionEl.classList.remove('hidden');
    setCatalogHead('📚 知识点目录', '绿点 = 可交互可视化<br>🔥🔥 = 最热考点（热门排行榜前 15）<br>🔥 = 考频高的重点（建议中）<br>考纲外 = 真题曾考、现行考纲已删<br>其余灰色 = 建设中，点击可看规划');
  }

  function setCatalogHead(title, hint) {
    if (catalogTitleEl) catalogTitleEl.textContent = title;
    if (catalogHintEl) catalogHintEl.innerHTML = hint;
  }

  /**
   * 索引页的侧栏：**年份快速定位**（按年份倒序，最新在上）+ 一个「全部年份」用于回到顶部。
   * 侧栏容器本身对索引页仍然有用（它是"按年份浏览"的另一半），故不隐藏它。
   */
  function renderIndexSidebar() {
    const years = (RC408.examIndex || []).map(r => r.y).sort((a, b) => b - a);
    sidebarEl.innerHTML =
      '<div class="sticky top-0 z-10 bg-white/95 backdrop-blur px-3 pt-3 pb-2 border-b border-slate-100">'
      + '<button data-iyear="all" class="w-full text-[11px] font-bold py-1.5 rounded-lg transition-colors '
      + (curIndexYear === null ? 'bg-indigo-500 text-white shadow-sm' : 'bg-slate-100 text-slate-500 hover:bg-slate-200')
      + '">全部年份（回到顶部）</button></div>'
      + years.map(y => `<button data-iyear="${y}" class="topic ${curIndexYear === y ? 'topic-active' : ''}">`
        + `<span class="dot dot-theory"></span><span>${y} 年</span></button>`).join('');
    sidebarEl.querySelectorAll('[data-iyear]').forEach(btn => {
      btn.addEventListener('click', () => {
        const v = btn.dataset.iyear;
        curIndexYear = v === 'all' ? null : +v;
        renderSidebar();
        if (v === 'all') indexSectionEl.scrollTop = 0;
        else RC408.examIndexPage.scrollToYear(+v);
      });
    });
    /* 移动端：同样给年份 */
    mobileEl.innerHTML = '<button data-iyear="all" class="shrink-0 px-3 py-1.5 rounded-lg text-xs font-bold bg-indigo-500 text-white">全部年份</button>'
      + years.map(y => `<button data-iyear="${y}" class="shrink-0 px-3 py-1.5 rounded-lg text-xs font-bold bg-slate-800 text-indigo-200">${y}</button>`).join('');
    mobileEl.querySelectorAll('[data-iyear]').forEach(btn => {
      btn.addEventListener('click', () => {
        const v = btn.dataset.iyear;
        curIndexYear = v === 'all' ? null : +v;
        if (v === 'all') indexSectionEl.scrollTop = 0;
        else RC408.examIndexPage.scrollToYear(+v);
      });
    });
  }

  /* ---- 启动 ---- */
  document.addEventListener('DOMContentLoaded', () => {
    Runner.mount();
    renderTabs();
    selectBook('ds');          // 默认打开【数据结构】的第一个可视化（**本窗没改这条**：打开网站仍默认它）
  });
})();
